/** Shared Hugeicons renderer; keeps existing layout and semantic icon names. */
export default function AppIcon({ name, className = "", style, ...props }: HTMLAttributes<HTMLElement> & { name?: string }) {
 const key = name ? `fa-${name}` : className.split(/\s+/).find(value => Object.hasOwn(icons, value));
 const icon = icons[key as keyof typeof icons] || InformationCircleIcon;
 return <i {...props} aria-hidden={props["aria-label"] ? undefined : true} role={props["aria-label"] ? "img" : undefined} className={`app-icon ${className}`} style={{ display: "inline-flex", alignItems: "center", justifyContent: "center", flexShrink: 0, fontStyle: "normal", verticalAlign: "-0.15em", ...style }}><HugeiconsIcon icon={icon} size="1em" strokeWidth={1.7} /></i>;
}
